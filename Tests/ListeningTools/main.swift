import Foundation

var timer = SleepTimerCountdown()
assert(timer.remaining(at: 100) == nil)
timer.start(minutes: 5, now: 100)
assert(timer.remaining(at: 100) == 300)
assert(timer.remaining(at: 130) == 270)
assert(!timer.consumeExpiry(at: 399.9))
assert(timer.consumeExpiry(at: 400))
assert(!timer.consumeExpiry(at: 401), "Expiry must be consumed exactly once")
timer.start(minutes: 1, now: 500)
timer.start(minutes: 10, now: 520)
assert(!timer.consumeExpiry(at: 560), "Replacing a timer must discard the old deadline")
timer.cancel()
assert(!timer.consumeExpiry(at: 2000), "Cancel must not pause later playback")
timer.start(minutes: 1, now: 3000)
assert(timer.consumeExpiry(at: 4000), "Delayed wake must consume overdue expiry")
timer.start(minutes: -1, now: 5000)
assert(timer.remaining(at: 5000) == nil)
timer.start(minutes: Int.max, now: 5000)
assert(timer.remaining(at: 5000) == nil)
timer.start(minutes: 30, now: .infinity)
assert(timer.remaining(at: 5000) == nil)
print("Sleep timer countdown regressions passed")
